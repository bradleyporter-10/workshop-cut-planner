const path = require('node:path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');
const result = esbuild.buildSync({
    absWorkingDir: root,
    entryPoints: ['scripts/skp-entry.mjs'],
    outfile: 'vendor/openskp/browser-bundle.js',
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: 'WorkshopSkp',
    target: ['es2020'],
    legalComments: 'eof',
    banner: { js: '// Generated by npm run build:skp. Runtime is fully local; no module loader or server required.' },
    metafile: true
});
for (const output of Object.values(result.metafile.outputs)) {
    if (output.imports.length) throw new Error('Offline bundle must not have external imports');
}
console.log('Built vendor/openskp/browser-bundle.js');
